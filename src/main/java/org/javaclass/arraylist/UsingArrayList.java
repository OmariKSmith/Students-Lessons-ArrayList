//-                                         ArrayList Methods

/*`


        Function	                Description	                        Example
`       add(E e)	                Adds an element to the end	        list.add("Apple");

`       add(int index, E element)	Inserts element at specific index	list.add(1, "Banana");
`
`       get(int index)	            Retrieves element at index	        list.get(0);
`
`       set(int index, E element)	Replaces element at index	        list.set(0, "Orange");
`
`       remove(int index)	        Removes element at index	        list.remove(2);
`
`       remove(Object o)	        Removes first occurrence of object	list.remove("Apple");
`
`       size()	                    Returns number of elements	        list.size();
`
`       isEmpty()	                Checks if list is empty	            list.isEmpty();
`
`       clear()	                    Removes all elements	            list.clear();
`
`       contains(Object o)	        Checks if element exists	        list.contains("Banana");
`
`       indexOf(Object o)	        Returns index of first occurrence	list.indexOf("Banana");
`
`       lastIndexOf(Object o)	    Returns index of last occurrence	list.lastIndexOf("Banana");
 */
